"""Writes the linear Bayer bin weights into native/raw_ingress/include/rawr/raw_ingress (BayerBinKernels.h,
BayerBinNoise.h) from fitted kernels (fit_linear_bin.py output).
usage: export_kernels.py <plain.npy> <sharp.npy> <native/raw_ingress directory>"""
import sys, numpy as np
plain, sharp = np.load(sys.argv[1]), np.load(sys.argv[2])
assert plain.shape == sharp.shape == (4, 12, 12)
# Noise table for BayerBinner::noiseVarianceGain: sum of squared plain weights by output colour
# (R, G averaged over both green phases, B) and source colour (R, G, B), RGGB window layout.
off = np.arange(12) - 5
wy, wx = np.meshgrid(off, off, indexing='ij')
srccol = np.array([[0, 1], [1, 2]])[wy & 1, wx & 1]
table = []
for phases in ((0,), (1, 2), (3,)):
    table.append([float(np.mean([(plain[q][srccol == c] ** 2).sum() for q in phases])) for c in range(3)])
hdr = sys.argv[3] + '/include/rawr/raw_ingress/BayerBinNoise.h'
rows = ', '.join('{' + ', '.join(f'{v:.9g}' for v in r) + '}' for r in table)
with open(hdr, 'w') as f:
    f.write(f"""#pragma once
// Generated by tools/bayer_bin_fit/export_kernels.py with the kernels in BayerBinKernels.h.
#include <array>
#include <cstdint>

namespace rawr::raw_ingress {{
// Sum of squared plain-kernel weights of the linear 2x Bayer bin, [output colour R, G, B][source colour R, G, B].
inline constexpr double kBayerBinNoiseWeights[3][3] = {{{rows}}};

// Noise variance of a flat-area output pixel of colour outColour (0 R, 1 G, 2 B) relative to one source
// pixel's, with white-balance gains (R, G, B): a source of colour c enters the balanced domain with variance
// times g_c^2, the output is divided by its own colour's gain. Assumes equal source variance in every colour.
inline double bayerBinNoiseVarianceGain(std::uint32_t outColour, const std::array<float, 3>& gains) {{
    if (outColour > 2 || !(gains[outColour] > 0)) return 1.0;
    double v = 0;
    for (int c = 0; c < 3; ++c) v += kBayerBinNoiseWeights[outColour][c] * double(gains[c]) * gains[c];
    return v / (double(gains[outColour]) * gains[outColour]);
}}
}}  // namespace rawr::raw_ingress
""")
# The same weights for C++ (reference implementations and tests).
kh = sys.argv[3] + '/include/rawr/raw_ingress/BayerBinKernels.h'
def carr(name, k): return f'inline constexpr float {name}[576] = {{' + ', '.join(f'{x:.9e}f' for x in k.astype(np.float32).ravel()) + '};\n'
with open(kh, 'w') as f:
    f.write('#pragma once\n// Generated by tools/bayer_bin_fit/export_kernels.py from fit_linear_bin.py (12x12; 4-px lines and 8x8\n'
            '// diagonal nulled, stopband penalty; sharp = target with unsharp mask 0.6). Uploaded to the GPU bin as a UBO.\n'
            '// [q*144 + ky*12 + kx]: RGGB output phase q, window row/column offsets -5..6 from source (2X, 2Y).\n'
            'namespace rawr::raw_ingress {\n' + carr('kBayerBinPlain', plain) + carr('kBayerBinSharpDelta', sharp - plain) + '}  // namespace rawr::raw_ingress\n')
