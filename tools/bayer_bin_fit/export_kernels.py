"""Writes the linear Bayer bin weights into native/raw_ingress/include/rawr/raw_ingress (BayerBinKernels.h,
BayerBinNoise.h) from fitted kernels (fit_linear_bin.py output): the 2x bin (12x12, ratio=2) and the direct
3x bin (17x17, ratio=3).
usage: export_kernels.py <bin2.npy> <bin3.npy> <native/raw_ingress directory>"""
import sys, numpy as np
bin2, bin3 = np.load(sys.argv[1]), np.load(sys.argv[2])
assert bin2.shape == (4, 12, 12) and bin3.shape == (4, 17, 17)
SITE = np.array([[0, 1], [1, 2]])
def noise_table(k, ratio):
    # Sum of squared weights by output colour (R, G averaged over both green phases, B) and source colour
    # (R, G, B). The window starts at ratio*X + c0 (c0 0 at ratio 2, 1 at ratio 3), RGGB layout.
    n = k.shape[1]
    off = np.arange(n) - (n // 2 - 1) if ratio == 2 else np.arange(n) - n // 2
    c0 = 0 if ratio == 2 else 1
    wy, wx = np.meshgrid(off, off, indexing='ij')
    def colours(q): return SITE[(ratio * (q >> 1) + c0 + wy) & 1, (ratio * (q & 1) + c0 + wx) & 1]
    return [[float(np.mean([(k[q][colours(q) == c] ** 2).sum() for q in phases])) for c in range(3)]
            for phases in ((0,), (1, 2), (3,))]
def rows(t): return ', '.join('{' + ', '.join(f'{v:.9g}' for v in r) + '}' for r in t)
hdr = sys.argv[3] + '/include/rawr/raw_ingress/BayerBinNoise.h'
with open(hdr, 'w') as f:
    f.write(f"""#pragma once
// Generated by tools/bayer_bin_fit/export_kernels.py with the kernels in BayerBinKernels.h.
#include <array>
#include <cstdint>

namespace rawr::raw_ingress {{
// Sum of squared kernel weights of the linear Bayer bins, [output colour R, G, B][source colour R, G, B]:
// the 2x bin and the direct 3x bin.
inline constexpr double kBayerBinNoiseWeights[3][3] = {{{rows(noise_table(bin2, 2))}}};
inline constexpr double kBayerBin3NoiseWeights[3][3] = {{{rows(noise_table(bin3, 3))}}};

// Noise variance of a flat-area output pixel of colour outColour (0 R, 1 G, 2 B) relative to one source
// pixel's, with white-balance gains (R, G, B): a source of colour c enters the balanced domain with variance
// times g_c^2, the output is divided by its own colour's gain. Assumes equal source variance in every colour.
// ratio: 2 or 3 (the bin's downscale per side).
inline double bayerBinNoiseVarianceGain(std::uint32_t outColour, const std::array<float, 3>& gains,
                                        std::uint32_t ratio = 2) {{
    if (outColour > 2 || !(gains[outColour] > 0)) return 1.0;
    const auto& w = ratio == 3 ? kBayerBin3NoiseWeights : kBayerBinNoiseWeights;
    double v = 0;
    for (int c = 0; c < 3; ++c) v += w[outColour][c] * double(gains[c]) * gains[c];
    return v / (double(gains[outColour]) * gains[outColour]);
}}
}}  // namespace rawr::raw_ingress
""")
# The same weights for C++ (reference implementations and tests).
kh = sys.argv[3] + '/include/rawr/raw_ingress/BayerBinKernels.h'
def carr(name, k): return f'inline constexpr float {name}[{k.size}] = {{' + ', '.join(f'{x:.9e}f' for x in k.astype(np.float32).ravel()) + '};\n'
with open(kh, 'w') as f:
    f.write('#pragma once\n// Generated by tools/bayer_bin_fit/export_kernels.py from fit_linear_bin.py (4-px lines and 8x8 diagonal\n'
            '// nulled, stopband penalty, colours kept apart at low frequencies). Uploaded to the GPU bins as UBOs.\n'
            '// kBayerBinPlain: 2x bin, [q*144 + ky*12 + kx], RGGB output phase q, window offsets -5..6 from source (2X, 2Y).\n'
            '// kBayerBin3: direct 3x bin, [q*289 + ky*17 + kx], window offsets -8..8 from source (3X+1, 3Y+1).\n'
            'namespace rawr::raw_ingress {\n' + carr('kBayerBinPlain', bin2) + carr('kBayerBin3', bin3) + '}  // namespace rawr::raw_ingress\n')
