"""Generates shaders/rx_tables.glsl: the VALID-Gaussian pyramid kernels of Rexture's alignment pyramid.
Same construction as the reference merge (`gauss_valid_decimate`): sigma = 0.5 * factor, radius = int(4 sigma + 0.5),
k[i] = exp(-i^2 / (2 sigma^2)) normalised in float64, rounded to float32. Factors: 2 (9 taps), 4 (17 taps).
Usage: python -I gen_gauss_tables.py > ../shaders/rx_tables.glsl   (numpy only)"""
import numpy as np

def kernel(factor):
    sigma = .5 * factor; r = int(4 * sigma + .5)
    i = np.arange(-r, r + 1, dtype=np.float64)
    k = np.exp(-i * i / (2 * sigma * sigma)); return (k / k.sum()).astype(np.float32)

def scipy_kernel(sigma):
    """scipy.ndimage.gaussian_filter1d weights (truncate 4): radius int(4 sigma + 0.5), exp(-0.5 x^2 / sigma^2) normalised."""
    r = int(4. * sigma + .5); x = np.arange(-r, r + 1, dtype=np.float64)
    k = np.exp(-.5 / (sigma * sigma) * x * x); return (k / k.sum()).astype(np.float32)

print('// Generated by tools/gen_gauss_tables.py (float64 construction, float32 values). Do not edit.')
for name, f in (('RX_K2', 2), ('RX_K4', 4)):
    k = kernel(f)
    print(f'const float {name}[{len(k)}] = float[{len(k)}](' + ', '.join(f'{float(v):.9e}' for v in k) + ');')
k = scipy_kernel(1.5)    # structure-tensor integration scale (CFG tensor_sigma), half-resolution pixels
print(f'const float RX_KT[{len(k)}] = float[{len(k)}](' + ', '.join(f'{float(v):.9e}' for v in k) + ');')

